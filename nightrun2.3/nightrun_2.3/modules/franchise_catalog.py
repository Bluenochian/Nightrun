def build_module_catalog(specs):
    seen = set()
    duplicates = []
    modules = []
    for spec in specs:
        module_id = spec.get("id")
        if module_id in seen:
            duplicates.append(module_id)
        seen.add(module_id)
        modules.append(make_specific_module(spec))
    if duplicates:
        repeated = ", ".join(sorted(set(duplicates)))
        raise ValueError(f"Duplicate franchise module id(s): {repeated}")
    return modules


